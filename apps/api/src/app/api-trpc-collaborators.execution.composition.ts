/**
 * The execution half of {@link ApiTrpcCollaborators}: the three application
 * slices a run is dispatched through, and the three port groups the
 * `workflow.*`, `optimization.*`, `experiments.*` and `evaluations.*`
 * namespaces reach for.
 *
 * Four packaged surfaces are served from one composition, and they are one
 * composition because they are one graph:
 *
 *   workflow.*      the studio's own lifecycle — versions, copies, publication
 *   optimization.*  the studio's component and evaluator publication panel
 *   experiments.*   the wizard and the workbench
 *   evaluations.*   the evaluator inventory and one trace's re-score
 *
 * The workflow SERVICE is read by the evaluator service (a workflow published
 * as an evaluator), by the experiment service (a wizard experiment writes
 * workflow versions) and by the workflow application itself. Composing it more
 * than once would give this process two answers to "what is the current
 * version of this workflow", and the one that drifts is always the copy — so
 * it is built here once and handed out.
 *
 * A fifth thing is composed here and reached from outside tRPC: the workbench
 * RUN LOOP. The surfaces that start a run are REST routes rather than
 * procedures, but every collaborator a run needs — the Experiment service, the
 * workflow service, the dataset, prompt, agent and evaluator services, and the
 * `reportEvaluation` sender — is already in this scope, so the run is composed
 * beside them (`api-experiment-run.composition.ts`) rather than over a second
 * graph that could disagree with what the namespaces answer.
 *
 * ## The NLP engine is one address, and everything runs on it
 *
 * A Studio run, a code evaluator and the evaluator keep-alive all reach the
 * SAME engine through the SAME port. That is deliberate: a code evaluator is a
 * one-node Studio graph, and giving it a second dispatch path is what lets two
 * paths disagree about which trace an evaluation's spans belong to — the
 * orphan-trace failure the `traceparent` header exists to prevent. With no
 * engine address configured the port refuses by name, and the surfaces that do
 * not execute anything keep working.
 *
 * ## What arrives as an option, and why
 *
 * The MODEL GATEWAY still arrives as a required input rather than being built
 * here, and it is now built by the process rather than by a host: the six
 * ports `PostgresModelProviderAdapter` needs are composed in
 * `api-model-provider.composition.ts` over this process's own graph. It stays
 * an input because ONE gateway serves the whole process — the REST families,
 * the packaged namespaces and this half all read the same provider rows — and
 * a second composed here would be a second answer to which credential a
 * provider holds. A Studio node's model is resolved per run, so an absent
 * gateway still makes this whole half absent, which is a named absence rather
 * than a degradation: a workflow namespace mounted over a gateway that does
 * not exist would answer every run with an unattributable failure.
 *
 * The rest degrade FAIL-CLOSED, each with its own reason:
 *
 *   - `runEvaluationForTrace` reaches the trace read pipeline and the caller's
 *     content protections, neither of which this process composes. Absent, a
 *     re-score refuses by name rather than scoring against an empty trace.
 *   - `generateCommitMessage` reaches the model gateway behind the studio's
 *     autogenerated message. Absent, it refuses, and the studio's own text box
 *     is the answer.
 *   - `mappingsSchema` and `coerceMonitorMappings` are the TRACE-MAPPING
 *     registry's, and that registry now lives in a browser package. Server code
 *     may not value-import one, so the two default to a permissive parse and
 *     the narrowing they would have done is named here rather than silently
 *     lost.
 *   - `workflowCreated` and `trackEvaluationRan` are product signals. Absent,
 *     nothing is recorded — smaller, not wrong.
 *   - `captureException` defaults to this composition's own logger rather than
 *     the deployment's error sink.
 */

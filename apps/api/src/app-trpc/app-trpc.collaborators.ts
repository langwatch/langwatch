/**
 * The `user.*` entries this process answers from its own Prisma connection:
 * the user rows behind the /me screens, the organization membership probe and
 * the first-project slug. Every one of them is a row read with a project or
 * user id already in hand, which is why they moved with the connection rather
 * than staying behind a port.
 *
 * The five that used to be here and are not any more — `rotatePassword`,
 * `tryFindAuth0DatabaseAccount`, `listLinkedAccounts` and `unlinkAccount`, and
 * the credential read and write the first replaced — are reads of `Account`,
 * the table the stored password hash lives on. They now reach the user
 * feature's own `UserCredentialService` and arrive as collaborators, which is
 * what the second half of this module's contract is for.
 */
type ApiOwnedUserPorts =
  | "emailIsTaken"
  | "isOrganizationMember"
  | "tryGetOrganizationName"
  | "tryGetUserContact"
  | "tryFindFirstProjectSlug";

export type ApiTrpcCollaborators<TSignUpDataSchema extends ZodTypeAny> = Readonly<{
  /**
   * The application slices every packaged surface reads off `ctx.app`.
   *
   * They arrive whole rather than one per feature: a request carries ONE
   * application, and a process that could hand a different slice to one
   * surface than to the one beside it would have two.
   */
  application: ApiTrpcFeatureApplication;

  /** The composed auth application both signed-out doors answer from. */
  auth: AuthApp;



  group: GroupTrpcPorts;


  identity: IdentityTrpcPorts;

  joinRequests: Omit<JoinRequestTrpcPorts, "listUserNames">;

  onboarding: OnboardingTrpcPorts<TSignUpDataSchema>;





  /** The forty-six answers `organization.*` needs from this deployment. */
  organization: OrganizationTrpcPorts<TSignUpDataSchema>;
  /** The audit-log read's own `kind: "custom"` check, already built. */
  organizationAuditLogCheck: unknown;
  /** The six answers `project.*` needs. */
  project: ProjectTrpcMountPorts;
  /** `project.create`'s custom tier resolution and the trace-sharing demand. */
  projectChecks: ProjectTrpcChecks;
  /** What one viewer may see of one project's captured content and spend. */
  codingAgents: CodingAgentTrpcPorts;
  /** The three answers the automation transport reaches beyond automation's own. */
  automation: AutomationMountPorts;
  /** The unsubscribe pair's client address, its throttle and its audit trail. */
  emailSuppression: EmailSuppressionTrpcPorts;
  /** The SCIM plan gate, and the back office's connection ledger with its trail. */
  enterprise: EnterpriseTrpcMountPorts;

  /**
   * The retention policy: who may write an override at a scope, which values
   * that scope's plan may persist, who may switch retention off, and the two
   * RBAC-filtered reads the settings page renders.
   */
  /** The monitor surface's precondition parser, comparison window and evaluator replication. */

  user: Omit<UserTrpcPorts, ApiOwnedUserPorts>;

}>;

/** What a set is missing, and therefore why the record is not mountable. */
export abstract class ApiTrpcCollaboratorGapReport {
  abstract incomplete(missing: readonly string[]): void;
}

/**
 * Reports the composition decision a missing collaborator set would otherwise
 * hide.
 *
 * One reason today and it is deliberately not a list of the individual
 * capabilities: they are one graph. A deployment holding the trace pipeline
 * but not the sign-in ceremony cannot serve `frontDoor`, and a record with
 * `frontDoor` missing is not a smaller record — it is a product a person
 * cannot sign in to. The absence is stated once, at the level a deployment can
 * actually act on.
 */
export abstract class ApiTrpcCollaboratorsAbsence {
  abstract absent(reason: "no-collaborators" | "no-database"): void;
}

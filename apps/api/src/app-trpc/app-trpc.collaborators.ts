/**
 * The capabilities the packaged tRPC record reaches that this process cannot
 * build for itself yet — enumerated, so "what is left" is a type rather than a
 * memory.
 *
 * `AppTrpcFeaturePorts` is the full list of what the twenty-two namespaces need
 * from their host. This is that list MINUS everything the API process now
 * answers out of its own composition: its Prisma connection, its audit sink,
 * its AuthZ service, and the several dozen row reads those three make possible.
 * What remains is not a leftover — every entry names a real capability with a
 * real owner, and the owner is a service no package holds today:
 *
 *   - the analytics input schemas and the filter catalogue, which are the
 *     deployment's and are shared with the REST analytics body;
 *   - the LangWatchQL workbench: its rollout gate, its statement executor and
 *     the tenant capability a restricted statement runs as;
 *   - the trace pipeline — reading a trace's content, resolving which ids a
 *     project holds, and the two annotation commands;
 *   - the sign-in ceremony, the sign-up ceremony and the invitation mailer;
 *   - the evaluator inventory, the evaluation runner and the NLP keep-alive;
 *   - the model gateway behind an autogenerated commit message;
 *   - the Enterprise governance surfaces, the billing store and the
 *     deployment's marketing notifications.
 *
 * A process that has none of them composes no record and says so by name; a
 * process that has them mounts all twenty-two. Nothing in between, and nothing
 * silently degraded — see {@link ApiTrpcCollaboratorsAbsence}.
 */

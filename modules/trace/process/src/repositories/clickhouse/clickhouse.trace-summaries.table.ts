import { column, defineClickHouseTable } from "@langwatch/clickhouse-client/builder";

/** Trace's folded summary per trace (goose 00002 onward), deduplicated on `UpdatedAt`. */
export const traceSummaries = defineClickHouseTable({
  name: "trace_summaries",
  tenantColumn: "TenantId",
  timeColumn: "OccurredAt",
  versionColumn: "UpdatedAt",
  sortKey: ["TenantId", "TraceId"],
  columns: {
    ProjectionId: column.string(),
    TenantId: column.string(),
    TraceId: column.string(),
    Version: column.lowCardinalityString(),
    Attributes: column.stringMap(),
    OccurredAt: column.dateTime64({ precision: 3 }),
    CreatedAt: column.dateTime64({ precision: 3 }),
    UpdatedAt: column.dateTime64({ precision: 3 }),
    ComputedIOSchemaVersion: column.lowCardinalityString(),
    ComputedInput: column.nullable(column.string()),
    ComputedOutput: column.nullable(column.string()),
    TimeToFirstTokenMs: column.nullable(column.uint32()),
    TimeToLastTokenMs: column.nullable(column.uint32()),
    TotalDurationMs: column.int64(),
    TokensPerSecond: column.nullable(column.uint32()),
    SpanCount: column.uint32(),
    ContainsErrorStatus: column.bool(),
    ContainsOKStatus: column.bool(),
    ErrorMessage: column.nullable(column.string()),
    Models: column.stringArray(),
    TotalCost: column.nullable(column.float64()),
    NonBilledCost: column.nullable(column.float64()),
    UnpricedSpanCount: column.uint32(),
    UnpricedModels: column.stringArray(),
    TokensEstimated: column.bool(),
    TotalPromptTokenCount: column.nullable(column.uint32()),
    TotalCompletionTokenCount: column.nullable(column.uint32()),
    OutputFromRootSpan: column.bool(),
    OutputSpanEndTimeMs: column.uint64(),
    BlockedByGuardrail: column.bool(),
    SatisfactionScore: column.nullable(column.float64()),
    TopicId: column.nullable(column.string()),
    SubTopicId: column.nullable(column.string()),
    HasAnnotation: column.nullable(column.bool()),
    AnnotationIds: column.stringArray(),
    LastEventOccurredAt: column.dateTime64({ precision: 3 }),
    TraceName: column.string(),
    RootSpanType: column.nullable(column.lowCardinalityString()),
    ContainsAi: column.bool(),
    ContainsPrompt: column.bool(),
    SelectedPromptId: column.nullable(column.string()),
    SelectedPromptSpanId: column.nullable(column.string()),
    LastUsedPromptId: column.nullable(column.string()),
    LastUsedPromptVersionNumber: column.nullable(column.uint32()),
    LastUsedPromptVersionId: column.nullable(column.string()),
    LastUsedPromptSpanId: column.nullable(column.string()),
    SourceType: column.lowCardinalityString(),
    SourceId: column.string(),
    EarliestSpanStartMs: column.uint64(),
    /** Goose 00130: the KSUID layout of ProjectionId; NULL on rows written before it. */
    IdLayout: column.nullable(column.lowCardinalityString()),
    /** The row's kept period in days; 0 keeps it forever. */
    _retention_days: column.uint16(),
    /** MATERIALIZED (goose 00032): read by the size facet and filter, never inserted. */
    _size_bytes: column.uint32(),
  },
});

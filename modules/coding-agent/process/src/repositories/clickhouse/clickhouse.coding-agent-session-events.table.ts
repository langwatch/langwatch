/**
 * `coding_agent_session_events`, owned by coding-agent (goose 00073, 00087, 00123):
 * ReplacingMergeTree(UpdatedAt) over (TenantId, SessionId, TimeUnixMs, RecordId),
 * partitioned by the week of TimeUnixMs.
 */
import { column, defineClickHouseTable } from "@langwatch/clickhouse-client/builder";

const moment = () => column.dateTime64({ precision: 3 });

export const codingAgentSessionEvents = defineClickHouseTable({
  name: "coding_agent_session_events",
  tenantColumn: "TenantId",
  versionColumn: "UpdatedAt",
  sortKey: ["TenantId", "SessionId", "TimeUnixMs", "RecordId"],
  columns: {
    TenantId: column.string(),
    SessionId: column.string(),
    TimeUnixMs: moment(),
    RecordId: column.fixedString({ length: 64 }),
    EventKind: column.lowCardinalityString(),
    Agent: column.lowCardinalityString(),
    SessionKeySource: column.lowCardinalityString(),
    TraceId: column.string(),
    SpanId: column.string(),
    PromptId: column.string(),
    QuerySource: column.lowCardinalityString(),
    AgentType: column.lowCardinalityString(),
    EventSequence: column.int64(),
    RequestId: column.string(),
    Model: column.lowCardinalityString(),
    InputTokens: column.uint64(),
    OutputTokens: column.uint64(),
    CacheReadTokens: column.uint64(),
    CacheCreationTokens: column.uint64(),
    CostUsd: column.float64(),
    DurationMs: column.uint32(),
    TtftMs: column.uint32(),
    Attempt: column.uint16(),
    Speed: column.lowCardinalityString(),
    StopReason: column.lowCardinalityString(),
    PreTokens: column.uint64(),
    PostTokens: column.uint64(),
    CompactionTrigger: column.lowCardinalityString(),
    PrecomputeReuse: column.lowCardinalityString(),
    StatusCode: column.lowCardinalityString(),
    ErrorType: column.lowCardinalityString(),
    RateLimitCarrier: column.lowCardinalityString(),
    RetryDurationMs: column.uint64(),
    ToolName: column.lowCardinalityString(),
    Success: column.lowCardinalityString(),
    Decision: column.lowCardinalityString(),
    DecisionSource: column.lowCardinalityString(),
    ToolInputBytes: column.uint64(),
    ToolResultBytes: column.uint64(),
    PromptChars: column.uint32(),
    TotalTokens: column.uint64(),
    UpdatedAt: moment(),
    _retention_days: column.uint16(),
    RepositoryHost: column.lowCardinalityString(),
    RepositoryOwner: column.lowCardinalityString(),
    RepositoryName: column.lowCardinalityString(),
    Branch: column.string(),
    AiUnits: column.float64(),
  },
});

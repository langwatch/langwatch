/**
 * `coding_agent_sessions`, owned by coding-agent (goose 00051, 00053, 00054, 00074, 00075, 00077,
 * 00083, 00085, 00096, 00099): ReplacingMergeTree(UpdatedAt) over (TenantId, StartedAt, SessionId),
 * partitioned by the week of StartedAt.
 */
import { column, defineClickHouseTable } from "@langwatch/clickhouse-client/builder";

const moment = () => column.dateTime64({ precision: 3 });
const labels = () => column.array(column.lowCardinalityString());
const counts = () => column.map({ key: column.lowCardinalityString(), value: column.uint32() });

export const codingAgentSessions = defineClickHouseTable({
  name: "coding_agent_sessions",
  tenantColumn: "TenantId",
  timeColumn: "StartedAt",
  versionColumn: "UpdatedAt",
  sortKey: ["TenantId", "StartedAt", "SessionId"],
  columns: {
    TenantId: column.string(),
    SessionId: column.string(),
    SessionKeySource: column.lowCardinalityString(),
    Version: column.lowCardinalityString(),
    StartedAt: moment(),
    CreatedAt: moment(),
    UpdatedAt: moment(),
    Agent: column.lowCardinalityString(),
    AgentVersion: column.lowCardinalityString(),
    TraceIds: column.stringArray(),
    FinalRequestId: column.string(),
    UserId: column.string(),
    TerminalType: column.lowCardinalityString(),
    Entrypoint: column.lowCardinalityString(),
    ModelCalls: column.uint32(),
    ToolCalls: column.uint32(),
    SubAgents: column.uint32(),
    Prompts: column.uint32(),
    PromptChars: column.uint64(),
    ResponseChars: column.uint64(),
    Steps: column.array(column.tuple(column.string(), column.uint32(), column.bool())),
    ToolCounts: counts(),
    ToolDurationMs: column.map({ key: column.lowCardinalityString(), value: column.uint64() }),
    FilesTouched: column.stringArray(),
    Skills: labels(),
    SubAgentTypes: labels(),
    SlashCommands: labels(),
    Models: labels(),
    McpServers: labels(),
    McpTools: labels(),
    InputTokens: column.uint64(),
    OutputTokens: column.uint64(),
    CacheReadTokens: column.uint64(),
    CacheCreationTokens: column.uint64(),
    CostUsd: column.float64(),
    ModelCallMs: column.uint64(),
    ToolMs: column.uint64(),
    TtftMsTotal: column.uint64(),
    TtftSamples: column.uint32(),
    BlockedOnUserMs: column.uint64(),
    ActiveTimeUserSec: column.uint64(),
    ActiveTimeCliSec: column.uint64(),
    ToolResultBytes: column.uint64(),
    ToolInputBytes: column.uint64(),
    Compactions: column.uint32(),
    CompactionTokensBefore: column.uint64(),
    CompactionTokensAfter: column.uint64(),
    PeakContextTokens: column.uint64(),
    CacheRebuildCount: column.uint32(),
    LargestCacheRebuildTokens: column.uint64(),
    FailedTools: column.uint32(),
    ErrorTypes: counts(),
    ApiErrors: column.uint32(),
    RateLimited: column.uint32(),
    RetriesExhausted: column.uint32(),
    RetryMs: column.uint64(),
    Attempts: column.uint32(),
    Refusals: column.uint32(),
    RefusalCategories: labels(),
    InternalErrors: column.uint32(),
    ToolsDenied: column.uint32(),
    ToolsAborted: column.uint32(),
    PermissionMode: column.lowCardinalityString(),
    PermissionChanges: column.uint32(),
    HooksBlocked: column.uint32(),
    HooksCancelled: column.uint32(),
    HookMs: column.uint64(),
    LinesAdded: column.uint64(),
    LinesRemoved: column.uint64(),
    Commits: column.uint32(),
    PullRequests: column.uint32(),
    EditsAccepted: column.uint32(),
    EditsRejected: column.uint32(),
    LanguagesEdited: labels(),
    AtMentions: column.uint32(),
    StopReason: column.lowCardinalityString(),
    Truncated: column.bool(),
    _retention_days: column.uint16(),
    SubAgentIds: column.stringArray(),
    PreviousCallContextTokens: column.uint64(),
    StepStartedAt: column.array(column.uint64()),
    MetricSeries: column.array(
      column.tuple(
        column.string(),
        column.string(),
        column.string(),
        column.string(),
        column.string(),
        column.float64(),
      ),
    ),
    LastEventOccurredAt: moment(),
    AppliedEventIds: column.stringArray(),
    RateLimitEvents: column.uint32(),
    CompactionTriggers: counts(),
    ParentSessionId: column.string(),
    IsFork: column.bool(),
    RepositoryHost: column.lowCardinalityString(),
    RepositoryOwner: column.lowCardinalityString(),
    RepositoryName: column.lowCardinalityString(),
    GitBranch: column.string(),
    GitWorktree: column.string(),
    Title: column.string(),
    GitBranches: column.stringArray(),
    TitleSource: column.lowCardinalityString(),
    AgentReportedCostUsd: column.float64(),
    Auxiliary: column.bool(),
    UsageByContext: column.array(
      column.tuple(
        column.string(),
        column.string(),
        column.string(),
        column.string(),
        column.uint64(),
        column.uint64(),
        column.uint64(),
        column.uint64(),
        column.float64(),
      ),
    ),
  },
});

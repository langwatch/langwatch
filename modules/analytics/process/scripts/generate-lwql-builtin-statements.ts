/**
 * Regenerates `lwql-builtin-statements.generated.ts`, grow-only: old hashes stay.
 * `--version <commit>=<json>` adds an older version's statements.
 * @see specs/lwql/query-origin.feature
 */

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { mergeCoverageCommits } from "../src/rules/lwql-builtin-statement-coverage.rules.ts";
import {
  LWQL_BUILTIN_STATEMENT_COVERAGE,
  LWQL_BUILTIN_STATEMENT_HASHES,
} from "../src/rules/lwql-builtin-statements.generated.ts";

const FIXTURE_PATH = fileURLToPath(
  new URL("../src/langwatch-ql/__tests__/fixtures/stock-widget-queries.json", import.meta.url),
);

const OUTPUT_PATH = fileURLToPath(
  new URL("../src/rules/lwql-builtin-statements.generated.ts", import.meta.url),
);

interface StockVersion {
  commit: string;
  sqls: string[];
}

function sqlsOf(path: string): string[] {
  return (JSON.parse(readFileSync(path, "utf8")) as { sql: string }[]).map(({ sql }) => sql);
}

/**
 * The commit that last changed the fixture. Refuses a fixture with uncommitted edits: `git log`
 * would name the previous commit for text it does not hold, so commit the fixture, then regenerate.
 */
function fixtureCommit(): string {
  const dirty = execFileSync("git", ["status", "--porcelain", "--", FIXTURE_PATH], {
    encoding: "utf8",
  }).trim();
  if (dirty !== "") {
    throw new Error("Commit the stock widget fixture before regenerating, so its commit is named.");
  }
  return execFileSync("git", ["log", "-1", "--format=%h", "--abbrev=11", "--", FIXTURE_PATH], {
    encoding: "utf8",
  }).trim();
}

function versionsFromArguments(): StockVersion[] {
  const extra = process.argv
    .slice(2)
    .flatMap((argument, index, all) => (all[index - 1] === "--version" ? [argument] : []));
  return extra.map((pair) => {
    const [commit = "", path = ""] = pair.split("=");
    return { commit, sqls: sqlsOf(path) };
  });
}

function main(): void {
  const newest: StockVersion = { commit: fixtureCommit(), sqls: sqlsOf(FIXTURE_PATH) };
  const older = versionsFromArguments();
  const commits = mergeCoverageCommits({
    existing: LWQL_BUILTIN_STATEMENT_COVERAGE.commits,
    newest: newest.commit,
    older: older.map(({ commit }) => commit),
  });
  const hashes = new Set(LWQL_BUILTIN_STATEMENT_HASHES);

  for (const { sqls } of [newest, ...older]) {
    for (const sql of sqls) hashes.add(createHash("sha256").update(sql).digest("hex"));
  }
  const oldestCommit = commits.at(-1) ?? "";

  writeFileSync(
    OUTPUT_PATH,
    `// Generated by scripts/generate-lwql-builtin-statements.ts; do not edit. Regenerate with it.
// Covers ${commits.length} stock statement versions, oldest commit ${oldestCommit}. Grow-only: a hash is never removed.

/** What the list covers: the commits whose stock text it holds (newest first), so a reader can tell how far back it goes. */
export const LWQL_BUILTIN_STATEMENT_COVERAGE = {
  versions: ${commits.length},
  oldestCommit: "${oldestCommit}",
  commits: ${JSON.stringify(commits)} as readonly string[],
} as const;

/** sha256 hex of every stock widget statement a saved widget has sent, as written. */
export const LWQL_BUILTIN_STATEMENT_HASHES: readonly string[] = ${JSON.stringify([...hashes].toSorted(), null, 2)};
`,
  );
  console.log(`wrote ${hashes.size} hashes over ${commits.length} versions to ${OUTPUT_PATH}`);
}

main();

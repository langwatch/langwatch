/** The whole LangWatchQL catalogue: every view a statement may name, and who may read it. */
export const LWQL_CATALOG = defineLwqlCatalog({
  ...LWQL_CLICKHOUSE_CATALOGUE,
  ...LWQL_POSTGRES_CATALOGUE,
});

/**
 * The column every LangWatchQL dataset names its owning tenant with. The fact tables because
 * that is their column, the PostgreSQL-engine tables because the approved view renamed the
 * application's `projectId` to match.
 */
export const TENANT_COLUMN = "TenantId";

/** A view's catalogue table, by the view name a statement uses. */
function catalogueTable(view: string): LwqlTableCatalogue {
  const tables: LwqlCatalogue = LWQL_CLICKHOUSE_CATALOGUE;
  const table = tables[view];
  if (table === undefined) throw new Error(`lwql view "${view}" has no catalogue table`);
  return table;
}

/** A hand-written view, gated as its catalogue table says. */
function handWrittenView(view: UngatedViewDefinition): LangWatchQLViewDefinition {
  return withCatalogueGates({ view, table: catalogueTable(view.name) });
}

/**
 * One derived view: its catalogue table decides the source, the exposed names and the gates;
 * `joinKeys` reaching another view are stated here.
 */
function clickhouseView(view: string, joinKeys?: readonly string[]): LangWatchQLViewDefinition {
  const table = catalogueTable(view);
  const exposed = exposedCatalogueColumns({ table });
  return defineCatalogTable(table.sourceTable, {
    ...CLICKHOUSE_OVERRIDES[table.sourceTable],
    name: view,
    ...(joinKeys ? { joinKeys } : {}),
    aliases: Object.fromEntries(
      exposed.filter((column) => column.name !== column.source).map((c) => [c.name, c.source]),
    ),
    skipColumns: Object.fromEntries(
      Object.entries(table.columns)
        .filter(([, entry]) => entry === "omit")
        .map(([name]) => [name, "omitted by the catalogue"]),
    ),
    columnGates: catalogueColumnGates({ table }),
  });
}


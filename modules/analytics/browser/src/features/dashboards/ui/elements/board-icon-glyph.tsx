export function BoardIconGlyph({
  icon,
  size,
  fallback,
}: {
  icon?: DashboardIcon | null;
  size: number;
  /** Drawn when the board has no icon. */
  fallback: ReactNode;
}) {
  // A reader older than the server may hold a name this record lacks, so it falls back too.
  const Glyph = icon ? BOARD_ICON_GLYPHS[icon] : undefined;
  if (!Glyph) return fallback;
  return <Glyph size={size} aria-hidden data-board-icon={icon} />;
}

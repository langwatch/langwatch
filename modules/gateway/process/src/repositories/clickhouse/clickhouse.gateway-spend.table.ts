/**
 * `gateway_spend`, owned by gateway (goose 00067, 00076, 00078, 00089, 00124):
 * ReplacingMergeTree(EventTimestamp) over (TenantId, GatewayRequestId), partitioned by OccurredAt.
 */
import { column, defineClickHouseTable } from "@langwatch/clickhouse-client/builder";

export const gatewaySpend = defineClickHouseTable({
  name: "gateway_spend",
  tenantColumn: "TenantId",
  timeColumn: "OccurredAt",
  versionColumn: "EventTimestamp",
  sortKey: ["TenantId", "GatewayRequestId"],
  columns: {
    TenantId: column.string(),
    GatewayRequestId: column.string(),
    OrganizationId: column.string(),
    VirtualKeyId: column.string(),
    PrincipalUserId: column.string(),
    EndUserId: column.string(),
    TraceId: column.string(),
    Model: column.string(),
    ProviderKey: column.string(),
    RequestType: column.lowCardinalityString(),
    Status: column.lowCardinalityString(),
    ErrorClass: column.lowCardinalityString(),
    HttpStatus: column.uint16(),
    NeedsReconciliation: column.uint8(),
    SettleReason: column.lowCardinalityString(),
    TokensInput: column.uint64(),
    TokensOutput: column.uint64(),
    TokensCacheRead: column.uint64(),
    TokensCacheWrite: column.uint64(),
    TokensReasoning: column.uint64(),
    CostNanoUSD: column.int64(),
    RateVersion: column.lowCardinalityString(),
    Labels: column.stringArray(),
    Metadata: column.string(),
    PodId: column.string(),
    PodSeq: column.uint64(),
    DurationMS: column.uint32(),
    OccurredAt: column.dateTime64({ precision: 3 }),
    Version: column.lowCardinalityString(),
    CreatedAt: column.uint64(),
    LastEventOccurredAt: column.uint64(),
    EventTimestamp: column.uint64(),
    MetadataMap: column.stringMap(),
    CharsInput: column.uint64(),
    AudioMS: column.uint64(),
    TokensCacheWrite1h: column.uint64(),
    TokensInputAudio: column.uint64(),
    TokensOutputAudio: column.uint64(),
    TokensInputImage: column.uint64(),
    TokensOutputImage: column.uint64(),
    ImageCount: column.uint64(),
    WebSearchRequests: column.uint64(),
  },
});

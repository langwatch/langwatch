// Generates src/tasks.generated.ts: a static map of task name -> dynamic import.
// task.ts used to discover tasks with readdirSync + a computed require, which the
// production bundle can't resolve (esbuild globs the whole dir, dragging in
// __tests__). A static registry works identically under tsx (dev) and the bundle.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const tasksDir = path.join(here, "..", "src", "tasks");
const out = path.join(here, "..", "src", "tasks.generated.ts");

// A task IS its default export — task.ts calls `script.default(...args)`. A
// module in this directory without one is a shared helper, not a task, so it
// gets no registry entry: entries are typed `() => Promise<TaskModule>`, and a
// helper would both fail that type and be inlined into the bundle for nothing.
/** @param {string} file @returns {boolean} */
const hasDefaultExport = (file) =>
  /^[ \t]*export\s+default\s|^[ \t]*export\s*\{[^}]*\bas\s+default\b/m.test(
    readFileSync(path.join(tasksDir, file), "utf8"),
  );

const candidates = readdirSync(tasksDir)
  // Real task modules only. A *.test.ts / *.spec.ts / *.d.ts sitting next to a
  // task would otherwise get a registry entry and be inlined into the bundle,
  // pulling vitest/testcontainers (now devDependencies) into the prod graph.
  .filter((f) => f.endsWith(".ts") && !/\.(d|test|spec)\.ts$/.test(f));

const names = candidates
  .filter(hasDefaultExport)
  .map((f) => f.replace(/\.ts$/, ""))
  .sort();

// Named, not silent: a task whose default export is missing or misspelled would
// otherwise vanish from the registry and only surface as "Task not found".
const skipped = candidates.filter((f) => !hasDefaultExport(f)).sort();
if (skipped.length > 0) {
  console.log(
    `  skipped (no default export, treated as helpers): ${skipped.join(", ")}`,
  );
}

const body = names
  .map((n) => `  ${JSON.stringify(n)}: () => import("./tasks/${n}"),`)
  .join("\n");

const contents = `// AUTO-GENERATED by scripts/generate-task-registry.mjs — do not edit.
// Regenerated as part of start:prepare:files. One static entry per module in
// src/tasks/, so both tsx (dev) and the esbuild bundle (prod) resolve tasks the
// same way, without a runtime directory scan.
// CLI args always arrive as strings, so string[] keeps each task's own
// signature (e.g. (projectId: string)) assignable here without using any.
type TaskModule = { default: (...args: string[]) => unknown };

export const TASKS: Record<string, () => Promise<TaskModule>> = {
${body}
};
`;

writeFileSync(out, contents);
console.log(
  `Wrote ${path.relative(path.join(here, ".."), out)} (${names.length} tasks)`,
);

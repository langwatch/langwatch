/**
 * Every handled-error code the TypeScript app can raise.
 *
 * This list exists so the presentation registry can be *exhaustive*: it is the
 * `Record` key set that `presentation.ts` must satisfy, which turns "someone
 * added an error code and never wrote the copy" from a runtime shrug into a
 * `pnpm typecheck` failure.
 *
 * Kept honest by `__tests__/codes.unit.test.ts`, which scans `src/`, `ee/` and
 * the workspace `packages/` for every code a `HandledError` subclass declares
 * and fails when this list and the code drift apart in either direction. All
 * three trees raise handled errors, and a scan that covers only one is a list
 * that silently stops being exhaustive. Adding a code here without
 * throwing it anywhere is just as much a bug as the reverse — it means dead
 * copy, which is how `recipient_not_in_team` survived in the automations
 * explainer for a code nothing raises.
 *
 * Codes declared by the Go services are NOT here — they come from
 * `goErrorCodes` in `@langwatch/handled-error`, generated by `cmd/herrgen`.
 *
 * Two entries are SCREAMING_CASE rather than the usual snake_case:
 * `LAST_WAY_IN` and `MFA_REQUIRED_BY_ORGANIZATION` are better-auth's own
 * `APIError` codes, thrown by `LastWayInGuard`
 * (`src/server/better-auth/last-way-in.ts`) on the mounted
 * `/passkey/delete-passkey` and `/two-factor/disable` routes. Neither path is
 * in `HANDLED_BY_BETTER_AUTH_CODE` (`src/server/better-auth/handled-errors.ts`),
 * so the code reaches the client exactly as better-auth wrote it — not
 * translated into one of our own `HandledError` subclasses. They are listed
 * here, spelled the way the wire actually sends them, so the presentation
 * registry has copy for them; see `codes.unit.test.ts`'s
 * `BETTER_AUTH_PASSTHROUGH_CODES` for why the usual raised/listed scan cannot
 * see them.
 */

// The comment-block grammar behind `langwatch/comment-block-size`. The caller
// supplies the comment ranges from the parser it already has; all below is pure.

// A file with no run of this many comment lines cannot hold an oversized block.
export const REVIEW_LINE_COUNT = 4;
export const MAX_COMMENT_BLOCK_LINES = 5;

const WHERE_IT_BELONGS =
  "Delete it when the code already says it, or move the narrative into an ADR under" +
  " `dev/docs/adr/` and leave one line here linking it.";

export const COMMENT_BLOCK_ERROR_WHAT =
  "Comment block has {{lines}} lines; the maximum is {{max}}.";

export const COMMENT_BLOCK_ERROR_FIX = `${WHERE_IT_BELONGS} See ADR-140.`;

/** The rendered message for a block of `lines`; retire once no test renders it by hand. */
export function commentBlockSizeMessage(lines) {
  return `${COMMENT_BLOCK_ERROR_WHAT} ${COMMENT_BLOCK_ERROR_FIX}`
    .replaceAll("{{lines}}", String(lines))
    .replaceAll("{{max}}", String(MAX_COMMENT_BLOCK_LINES));
}

export function marksGeneratedHeader(source) {
  const header = source.split("\n", 40).join("\n").toLowerCase();
  return /(?:@generated|code generated|generated (?:file|by)|auto-generated|autogenerated|automatically generated)/.test(
    header,
  );
}

export function marksLicenseHeader(source) {
  const header = source.split("\n", 80).join("\n").toLowerCase();
  if (header.includes("spdx-license-identifier")) return true;
  return header.includes("copyright") && /\blicen[cs](?:e|ed)\b/.test(header);
}

const DIRECTIVE_LINE = /^(?:\/\/|\/\*\*?|\*\/?|\*)?\s*(?:eslint-|oxlint-|@ts-)/;

const SCENARIO_ANNOTATION = /@scenario\b/;

/**
 * The JSDoc tags whose line count is set by the signature rather than by the
 * author: one per parameter, one per thrown type. `@deprecated` and `@example`
 * are not here - those carry prose, and prose is what the limit measures.
 */
const STRUCTURAL_TAG_LINE =
  /^\s*(?:\/\*\*)?\s*\*?\s*@(?:param|returns?|throws|template|typeParam|defaultValue|see|integration|vitest-environment|regression)\b/;

/** How many of a block's lines are structural JSDoc tags rather than commentary. */
export function structuralTagLines(text) {
  return text.split(/\r?\n/).filter((line) => STRUCTURAL_TAG_LINE.test(line)).length;
}

/**
 * Whether a line binds a test to a spec scenario. The title is quoted verbatim
 * on one line, so rewrapping it unbinds the test: such a line is measured by
 * neither the block limit nor the column limit.
 */
export function marksScenarioBinding(line) {
  return SCENARIO_ANNOTATION.test(line);
}

/**
 * A block is exempt when it is only lint/type-checker directives, or when it
 * carries a `@scenario` annotation binding a spec scenario to its test.
 */
export function isExemptBlock(text) {
  if (marksScenarioBinding(text)) return true;
  const lines = text
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line.length > 0 && line !== "/*" && line !== "*/" && line !== "/**");
  return lines.length > 0 && lines.every((line) => DIRECTIVE_LINE.test(line));
}

function isCommentLikeLine(line, insideBlockComment) {
  const text = line.trimStart();

  return insideBlockComment || text.startsWith("//") || text.startsWith("/*");
}

/** Whether a block comment is still open once `line` ends. */
function blockCommentOpenAfter(line, insideBlockComment) {
  const blockStart = line.indexOf("/*");
  const blockEnd = line.indexOf("*/", insideBlockComment ? 0 : blockStart + 2);
  if (insideBlockComment) return blockEnd === -1;

  return blockStart !== -1 && blockEnd === -1;
}

export function mayContainReviewBlock(source) {
  let contiguousLines = 0;
  let insideBlockComment = false;

  for (const line of source.split(/\r?\n/)) {
    contiguousLines = isCommentLikeLine(line, insideBlockComment) ? contiguousLines + 1 : 0;
    if (contiguousLines >= REVIEW_LINE_COUNT) return true;
    insideBlockComment = blockCommentOpenAfter(line, insideBlockComment);
  }
  return false;
}

/**
 * The character offset each line starts at, so a caller who already knows a
 * position can find its line with a binary search instead of re-splitting or
 * re-slicing the source once per lookup.
 */
export function lineIndex(source) {
  const starts = [0];
  for (let index = 0; index < source.length; index += 1) {
    const character = source[index];
    if (character === "\r" && source[index + 1] !== "\n") starts.push(index + 1);
    if (character === "\n") starts.push(index + 1);
  }
  return starts;
}

function lineAt(starts, position) {
  let lower = 0;
  let upper = starts.length - 1;
  while (lower <= upper) {
    const middle = Math.floor((lower + upper) / 2);
    const start = starts[middle];
    if (start === undefined || start > position) {
      upper = middle - 1;
    } else {
      lower = middle + 1;
    }
  }
  return upper;
}

/**
 * The 1-based line number containing `position`, the same number
 * `source.slice(0, position).split(/\r?\n/).length` would give — without the
 * O(file length) slice-and-split a caller doing that per lookup pays for.
 */
export function lineAtOffset(starts, position) {
  return lineAt(starts, position) + 1;
}

/** `source` with every comment's characters blanked, line breaks kept, so code is what remains. */
function blankComments(source, ranges) {
  let code = "";
  let cursor = 0;
  for (const { pos, end } of ranges) {
    code += source.slice(cursor, pos) + source.slice(pos, end).replaceAll(/[^\r\n]/g, " ");
    cursor = end;
  }

  return code + source.slice(cursor);
}

function commentLines(source, ranges) {
  const starts = lineIndex(source);
  const lines = blankComments(source, ranges)
    .split(/\r\n|\r|\n/)
    .map((text) => ({ hasCode: /[^ \t]/.test(text), hasComment: false }));

  for (const comment of ranges) {
    const start = lineAt(starts, comment.pos);
    const end = lineAt(starts, Math.max(comment.pos, comment.end - 1));
    for (let line = start; line <= end; line += 1) {
      const current = lines[line];
      if (current) current.hasComment = true;
    }
  }
  return lines;
}

/**
 * The contiguous runs of comment-only lines in `source`, as 1-based start
 * lines with a length. `ranges` are `{ pos, end }` offsets, sorted.
 */
export function collectCommentBlocks({ source, ranges }) {
  const blocks = [];
  const lines = commentLines(source, ranges);
  let start;

  const finish = (end) => {
    if (start === undefined) return;
    blocks.push({ line: start + 1, lines: end - start });
    start = undefined;
  };

  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index];
    const commentOnly = line?.hasComment && !line.hasCode;
    if (commentOnly) {
      start ??= index;
      continue;
    }
    finish(index);
  }
  finish(lines.length);
  return blocks;
}

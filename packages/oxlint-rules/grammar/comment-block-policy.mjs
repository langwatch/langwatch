// The comment-block grammar behind `langwatch/comment-block-size`. The caller
// supplies the comment ranges from the parser it already has; all below is pure.

export const MAX_COMMENT_BLOCK_LINES = 5;

const WHERE_IT_BELONGS =
  "Delete it when the code already says it, or move the narrative into an ADR under" +
  " `dev/docs/adr/` and leave one line here linking it.";

export const COMMENT_BLOCK_ERROR_WHAT =
  "Comment block has {{lines}} lines; the maximum is {{max}}.";

export const COMMENT_BLOCK_ERROR_WHY =
  "A comment is for what the code cannot say, and a long one is narrative that drifts from it.";

export const COMMENT_BLOCK_ERROR_FIX = `${WHERE_IT_BELONGS} See ADR-140.`;

/** The rendered message for a block of `lines`; retire once no test renders it by hand. */
export function commentBlockSizeMessage(lines) {
  return `${COMMENT_BLOCK_ERROR_WHAT} ${COMMENT_BLOCK_ERROR_WHY} ${COMMENT_BLOCK_ERROR_FIX}`
    .replaceAll("{{lines}}", String(lines))
    .replaceAll("{{max}}", String(MAX_COMMENT_BLOCK_LINES));
}

/** Whether the comments in a file's first 40 lines, joined, mark it as generated. */
export function marksGeneratedHeader(headerText) {
  const header = headerText.toLowerCase();
  return /(?:@generated|code generated|generated (?:file|by)|auto-generated|autogenerated|automatically generated)/.test(
    header,
  );
}

/** Whether the comments in a file's first 80 lines, joined, carry a licence. */
export function marksLicenseHeader(headerText) {
  const header = headerText.toLowerCase();
  if (header.includes("spdx-license-identifier")) return true;
  return header.includes("copyright") && /\blicen[cs](?:e|ed)\b/.test(header);
}

const DIRECTIVE_LINE = /^(?:\/\/|\/\*\*?|\*\/?|\*)?\s*(?:eslint-|oxlint-|@ts-)/;

const SCENARIO_ANNOTATION = /@scenario\b/;

/**
 * The JSDoc tags whose line count is set by the signature rather than by the
 * author: one per parameter, one per thrown type. `@deprecated` and `@example`
 * are not here - those carry prose, and prose is what the limit measures.
 */
const STRUCTURAL_TAG_LINE =
  /^\s*(?:\/\*\*)?\s*\*?\s*@(?:param|returns?|throws|template|typeParam|defaultValue|see|integration|vitest-environment|regression)\b/;

/** How many of a block's lines are structural JSDoc tags rather than commentary. */
export function structuralTagLines(text) {
  return text.split(/\r?\n/).filter((line) => STRUCTURAL_TAG_LINE.test(line)).length;
}

/**
 * Whether a line binds a test to a spec scenario. The title is quoted verbatim
 * on one line, so rewrapping it unbinds the test: such a line is measured by
 * neither the block limit nor the column limit.
 */
export function marksScenarioBinding(line) {
  return SCENARIO_ANNOTATION.test(line);
}

/**
 * A block is exempt when it is only lint/type-checker directives, or when it
 * carries a `@scenario` annotation binding a spec scenario to its test.
 */
export function isExemptBlock(text) {
  if (marksScenarioBinding(text)) return true;
  const lines = text
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line.length > 0 && line !== "/*" && line !== "*/" && line !== "/**");
  return lines.length > 0 && lines.every((line) => DIRECTIVE_LINE.test(line));
}

/**
 * @vitest-environment node
 * Tests the postinstall cleanup in install-check-shims.mjs as a real process:
 * it restores pnpm's launchers from the retired check-queue bin shims.
 */

import { spawnSync } from "node:child_process";
import {
  chmodSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { afterEach, beforeEach, describe, expect, it } from "vitest";

const HERE = path.dirname(fileURLToPath(import.meta.url));

const REPO_ROOT = path.resolve(HERE, "../../..");
const INSTALLER = path.join(REPO_ROOT, "dev/scripts/install-check-shims.mjs");

/** Stands in for pnpm's generated launcher: echoes how it was called. */
const LAUNCHER = `#!/bin/sh
echo "real $*"
`;

/** What an earlier installer left at the bin entry, with pnpm's launcher parked at `.real`. */
const LEGACY_SHIM = `#!/bin/sh
# langwatch-check-queue-shim, generated by dev/scripts/install-check-shims.mjs. Do not edit.
exec "$(dirname "$0")/$(basename "$0").real" "$@"
`;

let scratch: string;
let binDir: string;

beforeEach(() => {
  scratch = mkdtempSync(path.join(os.tmpdir(), "check-shims-test-"));
  binDir = path.join(scratch, "node_modules", ".bin");
  mkdirSync(binDir, { recursive: true });
});

afterEach(() => {
  rmSync(scratch, { recursive: true, force: true });
});

function writeLauncher(name: string, source = LAUNCHER): void {
  const file = path.join(binDir, name);
  writeFileSync(file, source, "utf8");
  chmodSync(file, 0o755);
}

function plantLegacyShim(name: string): void {
  writeLauncher(`${name}.real`);
  writeLauncher(name, LEGACY_SHIM);
}

function removeShims() {
  return spawnSync(process.execPath, [INSTALLER, "--remove", binDir], {
    encoding: "utf8",
  });
}

describe("retiring automatic check shims", () => {
  /** @scenario "Installing dependencies retires automatic bin shims" */
  it("restores the original executable and can run twice", () => {
    plantLegacyShim("tsc");

    expect(removeShims().status).toBe(0);
    const run = spawnSync(path.join(binDir, "tsc"), ["--version"], {
      encoding: "utf8",
    });
    expect(run.status).toBe(0);
    expect(run.stdout).toBe("real --version\n");
    expect(existsSync(path.join(binDir, "tsc.real"))).toBe(false);
    expect(removeShims().stderr).toBe("");
    expect(readFileSync(path.join(binDir, "tsc"), "utf8")).toBe(LAUNCHER);
  });

  /** @scenario "Cleanup preserves a newly generated launcher" */
  it("keeps a regenerated pnpm launcher even with a stale backup", () => {
    plantLegacyShim("tsc");
    const regenerated = "#!/bin/sh\necho new-compiler\n";
    writeLauncher("tsc", regenerated);

    expect(removeShims().status).toBe(0);
    expect(readFileSync(path.join(binDir, "tsc"), "utf8")).toBe(regenerated);
  });

  /** @scenario "Cleanup reports an incomplete legacy installation" */
  it("reports a missing backup without removing the current entry", () => {
    plantLegacyShim("tsc");
    rmSync(path.join(binDir, "tsc.real"));

    expect(removeShims().stderr).toContain("could not restore tsc");
    expect(readFileSync(path.join(binDir, "tsc"), "utf8")).toContain("langwatch-check-queue-shim");
  });
});

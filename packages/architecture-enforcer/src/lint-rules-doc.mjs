import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { rules } from "../oxlint-plugin.mjs";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** The workspace root, from this file's own location rather than `cwd`. */
export const workspaceRoot = resolve(packageRoot, "../..");

/** The rendered file, workspace-relative. */
export const LINT_RULES_DOC = "dev/docs/lint-rules.md";

function specPathFor(root, name) {
  const spec = `specs/tooling/lint-${name}.feature`;
  const bound = existsSync(join(root, spec));

  return bound ? spec : void 0;
}

function kindOf(rule) {
  return rule.meta.type === "suggestion" ? "style" : rule.meta.type;
}

function cell(value) {
  return value === void 0 ? "—" : `\`${JSON.stringify(value)}\``;
}

function optionsSection(options) {
  const entries = Object.entries(options ?? {});
  if (entries.length === 0) return ["Options: none.", ""];

  const rows = entries.map(
    ([name, definition]) =>
      `| \`${name}\` | ${definition.type} | ${cell(definition.default)} | ${definition.description ?? "—"} |`,
  );

  return ["| Option | Type | Default | Description |", "| --- | --- | --- | --- |", ...rows, ""];
}

function messageSection(id, definition) {
  const lines = [`- \`${id}\``, `  - what: ${definition.what}`, `  - fix: ${definition.fix}`];
  if (definition.why) lines.push(`  - why: ${definition.why}`);

  return lines;
}

function ruleSection(root, name, rule) {
  const docs = rule.meta.docs ?? {};
  const spec = specPathFor(root, name);
  const facts = [
    `- Kind: ${kindOf(rule)}`,
    `- Applies to: ${docs.applies ?? "every file"}`,
    `- Fixable: ${rule.meta.fixable ?? "no"}`,
    `- Spec: ${spec ? `\`${spec}\`` : "none yet"}`,
  ];
  const messages = Object.entries(docs.messages ?? {}).sort(([a], [b]) => a.localeCompare(b));

  return [
    `## \`langwatch/${name}\``,
    "",
    ...facts,
    "",
    ...optionsSection(docs.options),
    "Messages:",
    "",
    ...messages.flatMap(([id, definition]) => messageSection(id, definition)),
    "",
  ];
}

/** The whole document, from the plugin registry and the `defineRule` metadata it carries. */
export function renderLintRuleDocs(root = workspaceRoot) {
  const names = Object.keys(rules).sort((a, b) => a.localeCompare(b));
  const lines = [
    "# LangWatch lint rules",
    "",
    "<!-- Generated by `pnpm --filter @langwatch/architecture-enforcer docs`. Edit the rule in",
    "     `packages/oxlint-rules/src/rules` and regenerate; do not edit this file. -->",
    "",
    `Every rule the \`langwatch\` oxlint plugin registers (${names.length} of them), rendered from the`,
    "`defineRule` declaration each one is written in. A printed message is `what` followed by",
    "`fix`; `why` is documentation and the linter never prints it.",
    "",
    ...names.map((name) => `- [\`langwatch/${name}\`](#langwatch${name.replaceAll("-", "")})`),
    "",
    ...names.flatMap((name) => ruleSection(root, name, rules[name])),
  ];

  return `${lines.join("\n").trimEnd()}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = join(workspaceRoot, LINT_RULES_DOC);
  const rendered = renderLintRuleDocs();
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (current === rendered) {
    process.stdout.write(`architecture-enforcer: ${LINT_RULES_DOC} is up to date\n`);
  } else {
    writeFileSync(target, rendered);
    process.stdout.write(`architecture-enforcer: wrote ${LINT_RULES_DOC}\n`);
  }
}

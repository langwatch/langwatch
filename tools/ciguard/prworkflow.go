// PRCall is one product check pr.yml calls: its job key there and its file.
type PRCall struct {
	Key  string
	File string
}

// PRCalls are the product checks pr.yml starts, in the order it lists them.
var PRCalls = []PRCall{
	{Key: "app", File: "langwatch-app-ci.yml"},
	{Key: "e2e", File: "e2e-ci.yml"},
	{Key: "nlp", File: "langwatch-nlp-ci.yml"},
	{Key: "langevals", File: "langevals-ci.yml"},
	{Key: "mcp", File: "mcp-javascript-ci.yml"},
	{Key: "sdk-go", File: "sdk-go-ci.yml"},
	{Key: "sdk-javascript", File: "sdk-javascript-ci.yml"},
	{Key: "docs", File: "docs-ci.yml"},
	{Key: "codeql", File: "codeql.yml"},
	{Key: "clickhouse-serverless", File: "clickhouse-serverless.yml"},
}

const (
	// PRWorkflowFile is the one workflow a pull request starts for them.
	PRWorkflowFile = ".github/workflows/pr.yml"
	// PRFiltersFile is its path filter, generated by `go run ./cmd/prfilters`.
	PRFiltersFile = ".github/pr-filters.yml"
	detectChanges = "./.github/actions/detect-changes"
)

// PRAlways are paths whose change starts every called check.
var PRAlways = []string{PRWorkflowFile, PRFiltersFile}

// PRRequired are the checks main's ruleset and branch protection require
// (2026-10-23) that ci-complete posts until the ruleset requires it instead.
var PRRequired = []string{
	"langwatch-app-complete", "typecheck", "build", "e2e-complete", "langwatch-nlp-complete",
	"langevals-complete", "mcp-javascript-complete", "sdk-go-complete", "sdk-javascript-complete",
	"docs-complete", "codeql-complete", "clickhouse-serverless-complete",
}

type prFile struct {
	On          map[string]any     `yaml:"on"`
	Concurrency ciscan.Concurrency `yaml:"concurrency"`
	Jobs        map[string]prJob   `yaml:"jobs"`
}

type prJob struct {
	If      string            `yaml:"if"`
	Uses    string            `yaml:"uses"`
	Outputs map[string]string `yaml:"outputs"`
	Steps   []prStep          `yaml:"steps"`
}

// prStep is a step as these checks read it. Not ciscan.Step: its own
// decoding would drop `run:`.
type prStep struct {
	Uses string            `yaml:"uses"`
	With map[string]string `yaml:"with"`
	Env  map[string]string `yaml:"env"`
	Run  string            `yaml:"run"`
}

// postedContext is one `<context>=${{ needs.<call>.result }}` pair in RESULTS.
var postedContext = regexp.MustCompile(`([a-z0-9-]+)=\$\{\{`)

func loadPRFile(repoRoot, rel string) (*prFile, error) {
	raw, err := os.ReadFile(filepath.Join(repoRoot, rel))
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", rel, err)
	}
	var file prFile
	if err := yaml.Unmarshal(raw, &file); err != nil {
		return nil, fmt.Errorf("parse %s: %w", rel, err)
	}

	return &file, nil
}

// pathsOf is every path a workflow's detect-changes steps consult, in the
// order they first appear, followed by PRAlways.
func pathsOf(file *prFile, rel string) ([]string, error) {
	var paths []string
	for _, body := range filterBodies(file) {
		entries, err := filterEntries(body)
		if err != nil {
			return nil, fmt.Errorf("%s: detect-changes filters: %w", rel, err)
		}
		paths = append(paths, entries...)
	}
	if len(paths) == 0 {
		return nil, fmt.Errorf("%s: no detect-changes filter to read", rel)
	}

	return uniqueInOrder(append(paths, PRAlways...)), nil
}

// filterBodies are the `filters:` blocks of a workflow's detect-changes
// steps, jobs taken in name order so the output is stable.
func filterBodies(file *prFile) []string {
	var bodies []string
	for _, job := range slices.Sorted(maps.Keys(file.Jobs)) {
		for _, step := range file.Jobs[job].Steps {
			if step.Uses == detectChanges {
				bodies = append(bodies, step.With["filters"])
			}
		}
	}

	return bodies
}

// filterEntries are the paths under every key of one filters block.
func filterEntries(body string) ([]string, error) {
	var doc yaml.Node
	if err := yaml.Unmarshal([]byte(body), &doc); err != nil {
		return nil, err
	}
	if len(doc.Content) == 0 || doc.Content[0].Kind != yaml.MappingNode {
		return nil, errors.New("not a mapping of keys to paths")
	}
	// A node, not a map: keep the order the workflow lists its keys in.
	var entries []string
	mapping := doc.Content[0].Content
	for i := 1; i < len(mapping); i += 2 {
		var paths []string
		if err := mapping[i].Decode(&paths); err != nil {
			return nil, err
		}
		entries = append(entries, paths...)
	}

	return entries, nil
}

func uniqueInOrder(values []string) []string {
	seen := map[string]bool{}
	out := values[:0:0]
	for _, value := range values {
		if !seen[value] {
			seen[value] = true
			out = append(out, value)
		}
	}

	return out
}

// PRFilters is the content of PRFiltersFile: a key per called check, holding
// every path that check's own detect-changes steps consult.
func PRFilters(repoRoot string) (string, error) {
	var out strings.Builder
	out.WriteString("# Generated by `go run ./cmd/prfilters` from each called workflow's\n")
	out.WriteString("# detect-changes paths. Do not edit: ciguard's pr-workflow check fails when stale.\n")
	for _, call := range PRCalls {
		rel := filepath.ToSlash(filepath.Join(ciscan.WorkflowDir, call.File))
		file, err := loadPRFile(repoRoot, rel)
		if err != nil {
			return "", err
		}
		paths, err := pathsOf(file, rel)
		if err != nil {
			return "", err
		}
		fmt.Fprintf(&out, "%s:\n", call.Key)
		for _, path := range paths {
			fmt.Fprintf(&out, "  - %q\n", path) // double quotes, as oxfmt writes them
		}
	}

	return out.String(), nil
}

// PRWorkflow asserts pr.yml and the checks it calls keep the promises in
// specs/ci/one-pull-request-workflow.feature.
func PRWorkflow(repoRoot string) ([]string, error) {
	var problems []string
	want, err := PRFilters(repoRoot)
	if err != nil {
		return nil, err
	}
	have, _ := os.ReadFile(filepath.Join(repoRoot, PRFiltersFile))
	if string(have) != want {
		problems = append(problems, PRFiltersFile+" is stale: run `go run ./cmd/prfilters`")
	}

	pr, err := loadPRFile(repoRoot, PRWorkflowFile)
	if err != nil {
		return nil, err
	}
	keys := make([]string, 0, len(PRCalls))
	for _, call := range PRCalls {
		keys = append(keys, call.Key)
		found, err := callProblems(repoRoot, pr, call)
		if err != nil {
			return nil, err
		}
		problems = append(problems, found...)
	}

	return append(problems, completeProblems(pr, keys)...), nil
}

// callProblems: pr.yml calls the check on its own key, forced true in the
// merge queue, and the check itself keeps its promises.
func callProblems(repoRoot string, pr *prFile, call PRCall) ([]string, error) {
	rel := filepath.ToSlash(filepath.Join(ciscan.WorkflowDir, call.File))
	called, err := loadPRFile(repoRoot, rel)
	if err != nil {
		return nil, err
	}
	problems := calledProblems(rel, called)
	job, ok := pr.Jobs[call.Key]
	switch {
	case !ok || job.Uses != "./"+rel:
		problems = append(problems, fmt.Sprintf("%s: job %s does not call %s", PRWorkflowFile, call.Key, rel))
	case !strings.HasPrefix(job.If, fmt.Sprintf("needs.changes.outputs.%s == 'true'", call.Key)):
		problems = append(problems, fmt.Sprintf("%s: job %s is not started on its changes key", PRWorkflowFile, call.Key))
	}
	output := fmt.Sprintf("${{ steps.filter.outputs.%s || steps.force.outputs.all }}", call.Key)
	if pr.Jobs["changes"].Outputs[call.Key] != output {
		problems = append(problems, fmt.Sprintf("%s: changes output %s is not forced true in the merge queue", PRWorkflowFile, call.Key))
	}

	return problems, nil
}

// calledProblems: a called check starts no pull request run itself, and its
// concurrency group is its own, not the caller's name.
func calledProblems(rel string, called *prFile) []string {
	var problems []string
	if _, ok := called.On["workflow_call"]; !ok {
		problems = append(problems, rel+": cannot be called (no workflow_call)")
	}
	for _, trigger := range []string{"pull_request", "merge_group"} {
		if _, ok := called.On[trigger]; ok {
			problems = append(problems, fmt.Sprintf("%s: still starts on %s; pr.yml starts it", rel, trigger))
		}
	}
	if strings.Contains(strings.ReplaceAll(called.Concurrency.Group, " ", ""), "${{github.workflow}}") {
		problems = append(problems, rel+": concurrency group is named after the caller (github.workflow)")
	}

	return problems
}

// complete is what ci-complete posts and allows.
type complete struct {
	posted, skips               []string
	passesSkipped, failsChanges bool
}

func readComplete(pr *prFile) complete {
	var c complete
	for _, step := range pr.Jobs["ci-complete"].Steps {
		for _, match := range postedContext.FindAllStringSubmatch(step.Env["RESULTS"], -1) {
			c.posted = append(c.posted, match[1])
		}
		c.passesSkipped = c.passesSkipped || strings.Contains(step.Run, "success | skipped) state=success")
		c.failsChanges = c.failsChanges || step.Env["CHANGES"] == "${{ needs.changes.result }}" &&
			strings.Contains(step.Run, `[ "$CHANGES" = success ] || state=failure`)
		c.skips = append(c.skips, allowedSkips(step)...)
	}

	return c
}

func allowedSkips(step prStep) []string {
	if !strings.Contains(step.Uses, "alls-green") {
		return nil
	}
	var skips []string
	for skip := range strings.SplitSeq(step.With["allowed-skips"], ",") {
		skips = append(skips, strings.TrimSpace(skip))
	}

	return skips
}

// completeProblems: ci-complete posts every required check, a skipped call
// passing unless changes failed, and allows every call to be skipped.
func completeProblems(pr *prFile, keys []string) []string {
	var problems []string
	c := readComplete(pr)
	if !sameSet(c.posted, PRRequired) {
		problems = append(problems, fmt.Sprintf("%s: ci-complete posts %v, main requires %v", PRWorkflowFile, c.posted, PRRequired))
	}
	if !c.passesSkipped {
		problems = append(problems, PRWorkflowFile+": ci-complete does not count a skipped call as passed")
	}
	if !c.failsChanges {
		problems = append(problems, PRWorkflowFile+": ci-complete posts passes when changes failed and every call skipped")
	}
	if !sameSet(c.skips, keys) {
		problems = append(problems, fmt.Sprintf("%s: ci-complete allows skipping %v, pr.yml calls %v", PRWorkflowFile, c.skips, keys))
	}

	return problems
}

func sameSet(a, b []string) bool {
	return slices.Equal(slices.Sorted(slices.Values(a)), slices.Sorted(slices.Values(b)))
}

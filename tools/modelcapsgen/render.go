package modelcapsgen

import (
	"bytes"
	"fmt"
	"strconv"
	"strings"
)

const header = `// Code generated by cmd/modelcapsgen. DO NOT EDIT.
//
// Source: platform/app/src/server/modelProviders/llmModels.json
// (reasoningConfig.toolsIncompatibleOn). Regenerate with ` + "`make modelcapsgen`" + `.
//
// Each entry is a model whose provider rejects reasoning combined with
// function tools on the listed endpoints. Adding a model here is a
// registry edit plus a regeneration — no dispatch logic changes. The
// logic that consumes this table lives in reasoningcaps.go.

package litellm

// reasoningToolConflicts is keyed by the registry model id, lowercased.
// Lookup goes through reasoningToolConflictFor, which also resolves the
// bare (provider-stripped) form.
var reasoningToolConflicts = map[string]reasoningToolConflict{
`

const footer = `}
`

// Render returns the generated Go source for the capability table.
func Render(capabilities []Capability) []byte {
	var out bytes.Buffer
	out.WriteString(header)
	for _, capability := range capabilities {
		// Lowercased at generation so the runtime lookup, which
		// lowercases the inbound model id, cannot miss on case alone.
		key := strings.ToLower(capability.ModelID)
		fmt.Fprintf(&out, "\t%s: {\n", strconv.Quote(key))
		out.WriteString("\t\tconflictEndpoints: []string{")
		for i, endpoint := range capability.ConflictEndpoints {
			if i > 0 {
				out.WriteString(", ")
			}
			out.WriteString(strconv.Quote(endpoint))
		}
		out.WriteString("},\n")
		fmt.Fprintf(&out, "\t\tcanDisable:        %t,\n", capability.CanDisable)
		out.WriteString("\t},\n")
	}
	out.WriteString(footer)
	return out.Bytes()
}
